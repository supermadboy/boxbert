#!/usr/bin/env python3
"""Isolated visual proposal. Original machining and mount files stay untouched."""
import math
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
source = (HERE.parent / 'geometry.scad').read_text()
x, y, w, h = map(float, re.search(r'opening=\[([^]]+)\]', source)[1].split(','))
r = 2.0
# Follow the original rounded opening, displacing along its outward normals.
# Eight broad waves, 4 mm at the valleys and exactly 10 mm at the crests.
segments = []
def line(a, b, normal):
    length = math.dist(a, b)
    segments.append((length, lambda t: (a[0]+(b[0]-a[0])*t, a[1]+(b[1]-a[1])*t, *normal)))
def arc(c, angle):
    def at(t):
        a = math.radians(angle+90*t)
        return c[0]+r*math.cos(a), c[1]+r*math.sin(a), math.cos(a), math.sin(a)
    segments.append((math.pi*r/2, at))
line((x+r,y),(x+w-r,y),(0,-1))
arc((x+w-r,y+r),270)
line((x+w,y+r),(x+w,y+h-r),(1,0))
arc((x+w-r,y+h-r),0)
line((x+w-r,y+h),(x+r,y+h),(0,1))
arc((x+r,y+h-r),90)
line((x,y+h-r),(x,y+r),(-1,0))
arc((x+r,y+r),180)
perimeter = sum(s[0] for s in segments)
N = 1600
outer, inner, distances = [], [], []
for i in range(N):
    s = perimeter*i/N
    wave = 7+3*math.cos(2*math.pi*8*s/perimeter)
    rest = s
    for length, at in segments:
        if rest <= length+1e-9:
            px, py, nx, ny = at(rest/length)
            inner.append((px,py))
            outer.append((px+wave*nx,py+wave*ny))
            distances.append(wave)
            break
        rest -= length
# Independent rounded-rectangle signed-distance check at every outer vertex.
def sdf(p):
    qx = abs(p[0]-(x+w/2))-(w/2-r)
    qy = abs(p[1]-(y+h/2))-(h/2-r)
    return math.hypot(max(qx,0),max(qy,0))+min(max(qx,qy),0)-r
measured = [sdf(p) for p in outer]
assert abs(min(measured)-4)<1e-8 and abs(max(measured)-10)<1e-8
assert len(outer)==N
coords = ',\n'.join(f'[{a:.6f},{b:.6f}]' for a,b in outer)
(HERE/'wave-points.scad').write_text('// Generated by generate.py; dimensions in mm.\nwave_points=[\n'+coords+'\n];\n')
bounds = [min(p[0] for p in outer),min(p[1] for p in outer),max(p[0] for p in outer),max(p[1] for p in outer)]
(HERE/'checks.txt').write_text(f'VISUAL PROPOSAL ONLY — not machining approval\nSource opening: {w} x {h} mm, R{r}\nSamples: {N}; waves: 8\nAnalytical distance to original rounded opening: {min(measured):.6f} .. {max(measured):.6f} mm\nWave envelope: {bounds[2]-bounds[0]:.3f} x {bounds[3]-bounds[1]:.3f} mm\nRebate depth: 3 mm (unchanged)\nNo full-layout, cutter, hold-down or physical fit approval.\n')
# Dimensioned top view: bare rebate, without glass, so the wave is visible.
im = Image.new('RGB',(1400,1120),'#f6f3ec')
d = ImageDraw.Draw(im)
fontpath='/usr/share/fonts/TTF/DejaVuSans.ttf'
if not Path(fontpath).exists():
    fonts=list(Path('/nix/store').glob('*dejavu-fonts*/share/fonts/truetype/DejaVuSans.ttf'))
    fontpath=str(fonts[0]) if fonts else None
def font(size):
    return ImageFont.truetype(fontpath,size) if fontpath else ImageFont.load_default(size=size)
def text(pos,s,size=24,fill='#243c45'):
    d.text(pos,s,font=font(size),fill=fill)
scale=10
cx,cy=x+w/2,y+h/2
def xy(p): return (700+(p[0]-cx)*scale,575-(p[1]-cy)*scale)
def polygon(ps,fill): d.polygon([xy(p) for p in ps],fill=fill)
text((65,40),'PN532 | Wellenfalz – erster Formvorschlag',37)
text((65,100),'Draufsicht von außen · Falz offen dargestellt, ohne Plexiglas',23)
d.rounded_rectangle((160,170,1240,970),radius=16,fill='#dfc297')
# Restrained wood grain; all recess areas are drawn over it.
for yy in range(185,960,19):
    d.line([(175,yy),(1225,yy+5)],fill='#d5b689',width=1)
polygon(outer,'#af8659')
d.line([xy(p) for p in outer+[outer[0]]],fill='#785735',width=3)
polygon(inner,'#263d46')
d.line([xy(p) for p in inner+[inner[0]]],fill='#152c34',width=2)
text((480,515),'Durchbruch',30, '#f3f4ed')
text((480,557),f'{w:g} × {h:g} mm · R2',24,'#f3f4ed')
# First sample is an exact crest, with a normal pointing downwards.
a,b=xy(inner[0]),xy(outer[0])
d.line([a,b],fill='#fff8dc',width=3)
for p in (a,b): d.line([(p[0]-8,p[1]),(p[0]+8,p[1])],fill='#fff8dc',width=3)
text((b[0]+15,(a[1]+b[1])/2-14),'10 mm',24,'#fff8dc')
text((65,995),'Wellenberge: 10 mm vom Lochrand · Täler: 4 mm · Falztiefe: 3 mm',25)
text((65,1045),'Separate Vorschau. Bestehende CNC-Dateien und Halter unverändert.',22)
im.save(HERE/'top.png')
print((HERE/'checks.txt').read_text())
