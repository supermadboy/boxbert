"""Deterministic DejaVu 2.37 -> monochrome glyph rows. Run through generate-fonts.mjs."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import hashlib
ROOT = Path(__file__).resolve().parents[2]
CODES = list(range(32,127)) + list(range(160,256)) + [0x2026]
lines = ['// Generated by tools/tft/generate-fonts.py; DejaVu license: assets/tft/fonts/LICENSE', '#pragma once', '#include <stdint.h>', 'struct TftGlyph { uint32_t rows[24]; uint8_t advance; };']
for name, file, size in [('Bold16','DejaVuSans-Bold.ttf',16),('Regular12','DejaVuSans.ttf',12)]:
    path = ROOT/'assets/tft/fonts'/file
    font = ImageFont.truetype(str(path),size,layout_engine=ImageFont.Layout.BASIC)
    lines.append('// source sha256 '+hashlib.sha256(path.read_bytes()).hexdigest())
    lines.append('static const TftGlyph '+name+'[] = {')
    for cp in CODES:
        image=Image.new('L',(24,24)); draw=ImageDraw.Draw(image)
        draw.text((0,18),chr(cp),font=font,anchor='ls',fill=255,stroke_width=0)
        rows=[sum((1<<x) for x in range(24) if image.getpixel((x,y))>=128) for y in range(24)]
        advance=int(font.getlength(chr(cp))+0.5)
        lines.append('{ {'+','.join(hex(r) for r in rows)+'},'+str(advance)+'}, // U+'+format(cp,'04X'))
    lines.append('};')
(ROOT/'firmware/ui/FontData.h').write_text('\n'.join(lines)+'\n')
print('Generated 192 glyphs x 2 faces; threshold=128; 24x24 rows, baseline=18')
